import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const compile = source => ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 } }).outputText;
const url = source => `data:text/javascript;base64,${Buffer.from(source).toString('base64')}`;
const workflow = url(compile(await readFile(new URL('../lib/workflow.ts', import.meta.url), 'utf8')));
const source = compile(await readFile(new URL('../lib/space-board.ts', import.meta.url), 'utf8')).replace(/from ['"]\.\/workflow['"]/, `from "${workflow}"`);
const { columnFor, moveTargets, filterTickets, groupTickets } = await import(url(source));
assert.equal(columnFor('Created'), 'To Do'); assert.equal(columnFor('Done'), 'Done');
assert.equal(columnFor('Peer Review'), 'In Progress'); assert.equal(columnFor('QA Issue'), 'In Progress');
assert.deepEqual(moveTargets({ status: 'Created' }, 'In Progress'), []);
assert.deepEqual(moveTargets({ status: 'Open' }, 'In Progress'), ['Started']);
assert.deepEqual(moveTargets({ status: 'QA Started' }, 'Done'), ['Resolved']);
assert.deepEqual(moveTargets({ status: 'Peer Review' }, 'Done'), []);
const rows = [{ id: 1, key: 'INV-1', title: 'API', labels: 'contract', assigneeName: 'Rahul', priority: 'High', issueType: 'Task' }, { id: 2, key: 'INV-2', title: 'UI', labels: '', assigneeName: '', priority: 'Low', issueType: 'Bug' }];
const empty = { query: '', assignee: '', priority: '', type: '' };
assert.deepEqual(filterTickets(rows, { ...empty, query: 'CONTRACT', assignee: 'Rahul', priority: 'High' }).map(row => row.id), [1]);
assert.deepEqual(filterTickets(rows, { ...empty, assignee: 'Unassigned' }).map(row => row.id), [2]);
assert.equal(filterTickets(rows, { ...empty, query: 'missing' }).length, 0);
assert.equal(groupTickets(rows, 'assignee').flatMap(group => group.tickets).length, 2);
assert.equal(groupTickets(rows, 'none')[0].tickets.length, 2);
console.log('PASS: board mapping, permitted moves without skipping review, combined filters, unassigned filtering and lossless grouping.');
